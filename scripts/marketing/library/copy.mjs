export const libraryCopyByLocale = { 'zh-CN': zhCN, en: english }

function shape(value) {
  if (typeof value === 'function') return 'fn'
  if (Array.isArray(value)) return value.map(shape)
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map((key) => [key, shape(value[key])]))
  return typeof value
}

export function assertLibraryCopyParity() {
  if (JSON.stringify(shape(zhCN)) !== JSON.stringify(shape(english))) throw new Error('Locale parity error in library copy')
}
